// TestRecipeKeepsArgumentsWithSpacesWhole runs the generated justfile with the
// real `just` and a stand-in program that prints each argument it receives.
func TestRecipeKeepsArgumentsWithSpacesWhole(t *testing.T) {
	justBin, err := exec.LookPath("just")
	if err != nil {
		t.Skip("just is not installed")
	}
	dir := t.TempDir()
	script := "#!/bin/sh\nfor a in \"$@\"; do echo \"[$a]\"; done\n"
	if err := os.WriteFile(filepath.Join(dir, "prog"), []byte(script), 0o755); err != nil {
		t.Fatal(err)
	}
	file := just.New(&execx.FakeRunner{}).RecipeFile(filepath.Join(dir, "prog"), []string{"test"})
	if err := os.WriteFile(filepath.Join(dir, "justfile"), []byte(file.Body), 0o644); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command(justBin, "--justfile", filepath.Join(dir, "justfile"), "test", "-run", "a b")
	out, err := cmd.Output()
	if err != nil {
		t.Fatalf("just failed: %v", err)
	}
	if want := "[test]\n[-run]\n[a b]\n"; string(out) != want {
		t.Errorf("program saw %q, want %q", out, want)
	}
}
