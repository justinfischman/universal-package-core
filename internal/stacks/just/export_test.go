package just_test

import (
	"strings"
	"testing"

	"github.com/justinfischman/universal-package-core/internal/components/execx"
	"github.com/justinfischman/universal-package-core/internal/stacks/just"
)

func TestRecipeFileCallsProgramPerVerb(t *testing.T) {
	file := just.New(&execx.FakeRunner{}).RecipeFile("upc", []string{"build", "test"})
	if file.Name != "justfile" {
		t.Errorf("name = %q", file.Name)
	}
	for _, want := range []string{"default:\n    @just --list\n", "\nbuild *args:\n    upc build {{args}}\n", "\ntest *args:\n    upc test {{args}}\n", "Generated by `upc export`"} {
		if !strings.Contains(file.Body, want) {
			t.Errorf("body lacks %q:\n%s", want, file.Body)
		}
	}
}

