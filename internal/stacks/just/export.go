package just

import (
	"fmt"
	"strings"

	"github.com/justinfischman/universal-package-core/internal/core"
)

var _ core.RecipeExporter = (*Source)(nil)

// Exists implements core.RecipeExporter.
func (*Source) Exists(dir string) bool { return HasFile(dir) }

// RecipeFile implements core.RecipeExporter: one recipe per verb that runs
// `program verb`, with the recipe's own arguments passed through one by one
// (`set positional-arguments` and `"$@"`), so an argument containing spaces stays
// one argument.
func (*Source) RecipeFile(program string, verbs []string) core.RecipeFile {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by `%s export`; recipes call %s, which picks the project's tools.\n", program, program)
	b.WriteString("# Regenerate with `" + program + " export --force`.\n\n")
	b.WriteString("set positional-arguments\n\n")
	b.WriteString("default:\n    @just --list\n")
	for _, verb := range verbs {
		fmt.Fprintf(&b, "\n%s *args:\n    %s %s \"$@\"\n", verb, program, verb)
	}
	return core.RecipeFile{Name: fileNames[0], Body: b.String()}
}
